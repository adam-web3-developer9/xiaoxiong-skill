#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Error {
    pub code: String,
    pub message: String,
    pub details: Value,
}
impl Error {
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        Self {
            code: code.into(),
            message: message.into(),
            details: json!({}),
        }
    }
}
impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.code, self.message)
    }
}
impl std::error::Error for Error {}
pub type Result<T> = std::result::Result<T, Error>;
pub type HostFuture<'a, T> = Pin<Box<dyn Future<Output = Result<T>> + Send + 'a>>;

/// Client IDs are generated by Session and always have an independent agent:
/// namespace. invoke must apply the same native account/build/update guards as
/// desktop IPC, then invoke DesktopApi and publish its committed events once.
pub trait Host: Send + Sync {
    fn build_snapshot(&self, client_id: &str) -> Value;
    /// Internal account/profile epoch, never returned over the wire.
    fn authorization_context(&self) -> Result<String> {
        Err(Error::new(
            "AGENT_V2_UNAVAILABLE",
            "Host does not support application authorization",
        ))
    }
    fn negotiate_schema(&self, _client_id: &str, schema: u64) -> Result<Value> {
        if schema != 1 {
            return Err(Error::new("AGENT_SCHEMA_MISMATCH", "Unsupported schema"));
        }
        Ok(json!({"schemaVersion":1}))
    }
    fn bind_authorization(&self, _client_id: &str, _context: &str) -> Result<()> {
        Ok(())
    }
    fn verify_build(&self, client_id: &str, build_id: &str) -> Result<Value>;
    fn forget_build(&self, client_id: &str);
    fn invoke<'a>(
        &'a self,
        channel: &'a str,
        client_id: &'a str,
        args: Vec<Value>,
    ) -> HostFuture<'a, Value>;
    fn operation(&self, _record: Operation) {}
}

/// Correlation only. Request bodies, connection tokens and credential values
/// never enter the operation observer.
#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Operation {
    pub method: Option<String>,
    pub session_id: String,
    pub id: Option<Value>,
    pub command_id: Option<Value>,
    pub request_id: Option<Value>,
    pub task_id: Option<Value>,
    pub elapsed_ms: f64,
    pub result: String,
}

pub struct Session {
    root: PathBuf,
    token: String,
    allow_legacy: bool,
    client_id: String,
    authenticated: bool,
    v2_client: Option<Value>,
    v2_session: Option<String>,
    authorizations: Arc<Authorizations>,
    host: Arc<dyn Host>,
}
impl Session {
    pub fn new(root: PathBuf, token: String, host: Arc<dyn Host>) -> Self {
        Self {
            root,
            token,
            allow_legacy: false,
            client_id: format!("agent:{}", uuid::Uuid::new_v4()),
            authenticated: false,
            v2_client: None,
            v2_session: None,
            authorizations: Arc::new(Authorizations::default()),
            host,
        }
    }
    /// Explicit developer-only compatibility; normal application sessions must
    /// use v2 approval and cannot fall back to the legacy bearer token.
    pub fn with_legacy(mut self, allow: bool) -> Self {
        self.allow_legacy = allow;
        self
    }
    pub fn with_authorizations(mut self, authorizations: Arc<Authorizations>) -> Self {
        self.authorizations = authorizations;
        self
    }
    pub fn client_id(&self) -> &str {
        &self.client_id
    }
    pub async fn process_line(&mut self, bytes: &[u8]) -> Value {
        let parsed = serde_json::from_str(&String::from_utf8_lossy(bytes));
        match parsed {
            Ok(request) => self.request(request).await,
            Err(_) => {
                let error = Error::new("AGENT_INVALID_REQUEST", "Request must be JSON");
                self.record(&Value::Null, Instant::now(), &error.code);
                json!({"id":null,"ok":false,"error":error})
            }
        }
    }
    pub async fn request(&mut self, request: Value) -> Value {
        let at = Instant::now();
        let result = self.dispatch(&request).await;
        let outcome = result
            .as_ref()
            .map(|_| "succeeded")
            .unwrap_or_else(|error| error.code.as_str());
        self.record(&request, at, outcome);
        match result {
            Ok(result) => json!({"id":request["id"],"ok":true,"result":result}),
            Err(error) => json!({"id":request["id"],"ok":false,"error":error}),
        }
    }
    async fn dispatch(&mut self, request: &Value) -> Result<Value> {
        if !request.is_object()
            || !(request["id"].is_string() || request["id"].is_number())
            || !request["method"].is_string()
            || !request["params"].is_object()
        {
            return Err(Error::new(
                "AGENT_INVALID_REQUEST",
                "Request requires id, method and object params",
            ));
        }
        if self.v2_client.is_some()
            || (request["method"] == "hello" && request["params"]["protocol"] == 2)
        {
            return self.dispatch_v2(request).await;
        }
        if !self.allow_legacy {
            return Err(Error::new(
                "AGENT_LEGACY_DISABLED",
                "Legacy local development protocol is disabled; use application authorization",
            ));
        }
        if !valid_token(request["token"].as_str(), &self.token) {
            return Err(Error::new(
                "AGENT_UNAUTHORIZED",
                "Invalid Agent connection token",
            ));
        }
        let method = request["method"].as_str().unwrap();
        let params = &request["params"];
        if method == "hello" {
            if self.authenticated {
                return Err(Error::new(
                    "AGENT_ALREADY_CONNECTED",
                    "Connection has already completed its handshake",
                ));
            }
            if params["protocol"].as_f64() != Some(1.) {
                return Err(Error::new(
                    "AGENT_PROTOCOL_MISMATCH",
                    "Unsupported Agent protocol",
                ));
            }
            if !params["dataRoot"]
                .as_str()
                .is_some_and(|root| same_directory(root, &self.root))
            {
                return Err(Error::new(
                    "AGENT_DATA_ROOT_MISMATCH",
                    "Agent data directory does not match the application",
                ));
            }
            let current = self.host.build_snapshot(&self.client_id);
            let main = current["main"].as_str().unwrap_or("");
            // The shared build gate is sticky. A bad CLI build must never be
            // handed to verify(), where it could poison unrelated windows.
            if params["buildId"].as_str() != Some(main)
                || main.is_empty()
                || main.contains("+nobuild")
                || main.contains("unknown-version+")
            {
                let mut error = Error::new(
                    "BUILD_MISMATCH",
                    "Agent and application builds do not match",
                );
                error.details = json!({"main":current["main"],"client":if truth(&params["buildId"]){params["buildId"].clone()}else{Value::Null}});
                return Err(error);
            }
            let build = self
                .host
                .verify_build(&self.client_id, params["buildId"].as_str().unwrap())?;
            self.authenticated = true;
            return Ok(
                json!({"protocol":1,"sessionId":self.client_id,"dataRoot":self.root,"build":build}),
            );
        }
        if !self.authenticated {
            return Err(Error::new(
                "AGENT_HANDSHAKE_REQUIRED",
                "Complete hello before calling Agent methods",
            ));
        }
        routes::invoke(self.host.as_ref(), &self.client_id, method, params).await
    }
    async fn dispatch_v2(&mut self, request: &Value) -> Result<Value> {
        let method = request["method"].as_str().unwrap();
        let params = &request["params"];
        if method == "hello" {
            if self.authenticated || self.v2_client.is_some() {
                return Err(Error::new(
                    "AGENT_ALREADY_CONNECTED",
                    "Handshake already completed",
                ));
            }
            if params["protocol"] != 2
                || params["schemaVersion"] != 1
                || ["id", "name", "version"].iter().any(|key| {
                    params["client"][*key]
                        .as_str()
                        .is_none_or(|v| v.trim().is_empty())
                })
            {
                return Err(Error::new(
                    "AGENT_PROTOCOL_MISMATCH",
                    "Expected protocol 2, schemaVersion 1 and client id/name/version",
                ));
            }
            let build = self.host.negotiate_schema(&self.client_id, 1)?;
            self.v2_client = Some(
                json!({"id":params["client"]["id"],"name":params["client"]["name"],"version":params["client"]["version"]}),
            );
            return Ok(
                json!({"protocol":2,"schemaVersion":1,"sessionId":self.client_id,"build":build,"capabilities":v2_routes::capabilities()}),
            );
        }
        let context = self.host.authorization_context()?;
        let string = |key: &str| {
            params[key]
                .as_str()
                .ok_or_else(|| Error::new("AGENT_INVALID_REQUEST", format!("{key} is required")))
        };
        match method {
            "auth.request" => {
                return self.authorizations.request(
                    self.v2_client.clone().unwrap(),
                    params,
                    context,
                )
            }
            "auth.poll" => {
                return self.authorizations.poll(
                    string("requestId")?,
                    string("pollSecret")?,
                    &context,
                )
            }
            "auth.resume" => {
                let grant = self.authorizations.authenticate(
                    string("sessionId")?,
                    string("token")?,
                    &context,
                )?;
                if grant.client != *self.v2_client.as_ref().unwrap() {
                    return Err(Error::new(
                        "AGENT_UNAUTHORIZED",
                        "Client identity differs from approved client",
                    ));
                }
                self.host.bind_authorization(&self.client_id, &context)?;
                self.v2_session = Some(grant.session_id.clone());
                return Ok(serde_json::to_value(grant).unwrap());
            }
            _ => {}
        }
        let id = self.v2_session.as_deref().ok_or_else(|| {
            Error::new(
                "AGENT_AUTH_REQUIRED",
                "Complete application approval and auth.resume",
            )
        })?;
        let grant = self.authorizations.authenticate(
            id,
            request["token"].as_str().unwrap_or(""),
            &context,
        )?;
        if method == "auth.logout" {
            self.authorizations.revoke(id);
            self.v2_session = None;
            return Ok(json!({"loggedOut":true}));
        }
        v2_routes::invoke(self.host.as_ref(), &self.client_id, method, params, &grant).await
    }
    fn record(&self, request: &Value, at: Instant, outcome: &str) {
        let record = Operation {
            method: request["method"].as_str().map(str::to_owned),
            session_id: self.client_id.clone(),
            id: request.get("id").cloned(),
            command_id: request["params"].get("commandId").cloned(),
            request_id: request["params"].get("requestId").cloned(),
            task_id: request["params"].get("taskId").cloned(),
            elapsed_ms: at.elapsed().as_secs_f64() * 1000.,
            result: outcome.into(),
        };
        let _ =
            std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| self.host.operation(record)));
    }
}
impl Drop for Session {
    fn drop(&mut self) {
        self.host.forget_build(&self.client_id);
    }
}

fn valid_token(supplied: Option<&str>, expected: &str) -> bool {
    let Some(supplied) = supplied else {
        return false;
    };
    supplied.len() == expected.len()
        && supplied
            .bytes()
            .zip(expected.bytes())
            .fold(0u8, |all, (a, b)| all | (a ^ b))
            == 0
}
pub(crate) fn truth(value: &Value) -> bool {
    match value {
        Value::Null => false,
        Value::Bool(value) => *value,
        Value::Number(value) => value.as_f64() != Some(0.),
        Value::String(value) => !value.is_empty(),
        _ => true,
    }
}
pub(crate) fn resolve_path(path: &Path) -> std::io::Result<PathBuf> {
    let absolute = std::path::absolute(path)?;
    let mut normalized = PathBuf::new();
    for component in absolute.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                normalized.pop();
            }
            component => normalized.push(component.as_os_str()),
        }
    }
    Ok(normalized)
}
fn same_directory(raw: &str, root: &Path) -> bool {
    if raw.is_empty() {
        return false;
    }
    resolve_path(Path::new(raw)).ok().is_some_and(|path| {
        if cfg!(windows) {
            path.to_string_lossy().to_lowercase() == root.to_string_lossy().to_lowercase()
        } else {
            path == root
        }
    })
}

#[cfg(test)]
mod v2_session_tests {
    use super::*;
    struct TestHost;
    impl Host for TestHost {
        fn build_snapshot(&self, _: &str) -> Value {
            json!({"main":"3.1.74+test"})
        }
        fn verify_build(&self, _: &str, _: &str) -> Result<Value> {
            panic!("v2 must never impersonate a renderer build")
        }
        fn forget_build(&self, _: &str) {}
        fn authorization_context(&self) -> Result<String> {
            Ok("account:epoch:1".into())
        }
        fn invoke<'a>(
            &'a self,
            channel: &'a str,
            _: &'a str,
            _: Vec<Value>,
        ) -> HostFuture<'a, Value> {
            Box::pin(async move {
                if channel == "local-data:drafts-get" {
                    Ok(json!({"id":"draft-1"}))
                } else {
                    Err(Error::new("TEST_UNEXPECTED_CHANNEL", channel))
                }
            })
        }
    }
    fn request(method: &str, params: Value) -> Value {
        json!({"id":1,"method":method,"params":params})
    }
    #[tokio::test]
    async fn legacy_token_cannot_bypass_v2_approval_by_default() {
        let mut session = Session::new(
            PathBuf::from("/tmp/test-agent"),
            "legacy-private".into(),
            Arc::new(TestHost),
        );
        let mut hello = request(
            "hello",
            json!({"protocol":1,"buildId":"3.1.74+test","dataRoot":"/tmp/test-agent"}),
        );
        hello["token"] = json!("legacy-private");
        assert_eq!(
            session.request(hello).await["error"]["code"],
            "AGENT_LEGACY_DISABLED"
        );
    }
    #[cfg(unix)]
    #[tokio::test(flavor = "multi_thread")]
    async fn actual_unix_socket_serves_v2_and_publishes_no_credentials() {
        let runtime = tokio::runtime::Handle::current();
        tokio::task::spawn_blocking(move || {
            use std::io::{BufRead, BufReader, Write};
            let root = std::env::temp_dir().join(format!("aistudio-v2-test-{}", uuid::Uuid::new_v4()));
            let mut server = Server::start(Options { data_root: root.clone(), temporary_directory: std::env::temp_dir() }, Arc::new(TestHost), runtime).unwrap();
            let descriptor: Value = serde_json::from_slice(&std::fs::read(root.join("agent-v2-connection.json")).unwrap()).unwrap();
            assert_eq!(descriptor["protocol"], 2);
            assert!(descriptor.get("token").is_none());
            let mut stream = std::os::unix::net::UnixStream::connect(descriptor["endpoint"].as_str().unwrap()).unwrap();
            stream.set_read_timeout(Some(std::time::Duration::from_secs(5))).unwrap();
            let mut reader = BufReader::new(stream.try_clone().unwrap());
            let mut exchange = |request: Value| -> Value {
                writeln!(stream, "{}", request).unwrap();
                let mut line = String::new(); reader.read_line(&mut line).unwrap(); serde_json::from_str(&line).unwrap()
            };
            assert_eq!(exchange(request("hello", json!({"protocol":2,"schemaVersion":1,"client":{"id":"cli","name":"CLI","version":"1"}})))["ok"], true);
            let pair = exchange(request("auth.request", json!({"scopes":["read"],"draftIds":["draft-1"]})))["result"].clone();
            server.authorizations().decide(pair["requestId"].as_str().unwrap(), true, "account:epoch:1").unwrap();
            let grant = exchange(request("auth.poll", json!({"requestId":pair["requestId"],"pollSecret":pair["pollSecret"]})))["result"].clone();
            assert_eq!(exchange(request("auth.resume", json!({"sessionId":grant["sessionId"],"token":grant["token"]})))["ok"], true);
            let mut read = request("draft.get", json!({"draftId":"draft-1"})); read["token"] = grant["token"].clone();
            assert_eq!(exchange(read)["result"]["id"], "draft-1");
            drop(exchange); drop(reader); drop(stream);
            server.close().unwrap();
            assert!(!root.join("agent-v2-connection.json").exists());
            assert!(!root.join("agent-data-connection.json").exists());
            std::fs::remove_dir_all(root).unwrap();
        }).await.unwrap();
    }
    #[tokio::test]
    async fn independent_client_requires_app_approval_then_revocation_takes_effect() {
        let auth = Arc::new(Authorizations::default());
        let mut session = Session::new(
            PathBuf::from("/tmp/test-agent"),
            "legacy-private".into(),
            Arc::new(TestHost),
        )
        .with_authorizations(auth.clone());
        let hello=session.request(request("hello",json!({"protocol":2,"schemaVersion":1,"client":{"id":"cli","name":"CLI","version":"9.0.0-independent"}}))).await;
        assert_eq!(hello["ok"], true);
        assert_eq!(
            session
                .request(request("draft.get", json!({"draftId":"draft-1"})))
                .await["error"]["code"],
            "AGENT_AUTH_REQUIRED"
        );
        let paired = session
            .request(request(
                "auth.request",
                json!({"scopes":["read"],"draftIds":["draft-1"]}),
            ))
            .await["result"]
            .clone();
        assert_eq!(
            session
                .request(request(
                    "auth.approve",
                    json!({"requestId":paired["requestId"]})
                ))
                .await["ok"],
            false
        );
        auth.decide(
            paired["requestId"].as_str().unwrap(),
            true,
            "account:epoch:1",
        )
        .unwrap();
        let granted = session
            .request(request(
                "auth.poll",
                json!({"requestId":paired["requestId"],"pollSecret":paired["pollSecret"]}),
            ))
            .await["result"]
            .clone();
        assert_eq!(
            session
                .request(request(
                    "auth.resume",
                    json!({"sessionId":granted["sessionId"],"token":granted["token"]})
                ))
                .await["ok"],
            true
        );
        let mut read = request("draft.get", json!({"draftId":"draft-1"}));
        read["token"] = granted["token"].clone();
        assert_eq!(session.request(read.clone()).await["ok"], true);
        auth.revoke(granted["sessionId"].as_str().unwrap());
        assert_eq!(
            session.request(read).await["error"]["code"],
            "AGENT_UNAUTHORIZED"
        );
    }
}
